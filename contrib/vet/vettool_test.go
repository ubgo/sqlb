package vet_test

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

// TestVettool_RunsUnderGoVet builds cmd/sqlbvet and drives it through go vet
// -vettool, which is the only way a unitchecker main is verified, since it
// does nothing outside the vet protocol.
//
// The packages it vets are generated with unique content on every run. That
// is not cosmetic: go 1.27's vet cache keys a package's result without the
// custom tool's output in it, so a second go vet -vettool over an unchanged
// package replays an empty result, and a plain go vet ./... beforehand, as
// task check runs, does the same. A package no cache has seen is the only
// invocation this test can trust; the README says the same to users.
func TestVettool_RunsUnderGoVet(t *testing.T) {
	bin := filepath.Join(t.TempDir(), "sqlbvet")
	if out, err := exec.Command("go", "build", "-o", bin, "./cmd/sqlbvet").CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	stamp := fmt.Sprintf("%d", time.Now().UnixNano())
	dir := filepath.Join("internal", "probe", "vettool_"+stamp)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(dir) })
	write := func(name, body string) string {
		sub := filepath.Join(dir, name)
		if err := os.MkdirAll(sub, 0o755); err != nil {
			t.Fatal(err)
		}
		src := "// Generated by TestVettool_RunsUnderGoVet at " + stamp + ".\npackage " + name + "\n\n" + body
		if err := os.WriteFile(filepath.Join(sub, name+".go"), []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		return "./" + filepath.ToSlash(sub)
	}
	clean := write("clean", `import "github.com/ubgo/sqlb/sqlite"

func Q() *sqlite.SelectQuery { return sqlite.Select() }
`)
	mixed := write("mixed", `import (
	"github.com/ubgo/sqlb"
	"github.com/ubgo/sqlb/sqlite"
	"github.com/ubgo/sqlb/pg"
)

var t = sqlb.Table{Name: "t", Alias: "t"}
var c = sqlb.Col[string](t, "c")

func Q() *sqlite.SelectQuery { return sqlite.Select().Exprs(pg.ArrayAgg(c)).From(t) }
`)
	run := func(pkg string) string {
		out, _ := exec.Command("go", "vet", "-vettool="+bin, pkg).CombinedOutput()
		return string(out)
	}
	if rest := diagnostics(run(clean)); rest != "" {
		t.Fatalf("clean package should produce no diagnostic under go vet, got:\n%s", rest)
	}
	if out := run(mixed); !strings.Contains(out, "postgres construct ArrayAgg in a statement fixed to sqlite") {
		t.Fatalf("expected the dialect finding in go vet's output:\n%s", out)
	}
}

// diagnostics strips go vet's package headers and JSON scaffolding, leaving
// only diagnostic text, so the assertion holds in either output mode.
func diagnostics(out string) string {
	var kept []string
	for _, line := range strings.Split(out, "\n") {
		l := strings.TrimSpace(line)
		if l == "" || strings.HasPrefix(l, "#") || l == "{" || l == "}" || l == "{}" {
			continue
		}
		kept = append(kept, l)
	}
	return strings.Join(kept, "\n")
}
