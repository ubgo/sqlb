package structbind

import (
	"strings"
	"unicode"
)

// Namer derives a column name from a Go field name.
//
// It is the fallback for a field with no db tag, never an override: a tag is
// what somebody wrote down deliberately, so it always wins.
//
// This is a parameter rather than a package-level setting on purpose. Other
// mappers put the equivalent on the handle as a package-wide function, which
// makes the meaning of a
// struct depend on mutable state somewhere else in the process; two libraries
// sharing a handle then fight over it, and the loser's columns are wrong at
// runtime with nothing to point at. Passing it to New keeps one Mapping's
// answer knowable from one call site.
type Namer func(goFieldName string) string

// Snake converts a Go field name to snake_case, and is the default.
//
// It is the default because it is the convention SQL itself uses and the one
// most schemas follow, but it is only a default: a column genuinely named
// "createdAt" is common in schemas generated by JavaScript tooling, which is
// why Camel exists and why any func is accepted.
//
// A run of capitals is one word, so HTTPStatus is http_status rather than
// h_t_t_p_status, and a trailing lowercase s belongs to the run before it, so
// URLs is urls rather than ur_ls. Both rules exist because the alternative
// produced names no database has ever had.
//
// It has no list of known initialisms, deliberately. Such a list is a decision
// about somebody else's vocabulary that can never be complete, and it would
// make the output depend on whether a word happened to be in it. OAuth2Token
// becomes o_auth2_token rather than oauth2_token; when the derivation is wrong
// the answer is a db tag, which is exact and local and already the documented
// escape hatch.
func Snake(name string) string {
	return strings.Join(lowerWords(name), "_")
}

// Camel converts a Go field name to camelCase: createdAt, userId.
//
// For a schema whose columns are camelCase, which is what JavaScript-side
// tooling generates. The same word splitting as Snake, so
// HTTPStatus is httpStatus rather than hTTPStatus.
func Camel(name string) string {
	words := lowerWords(name)
	for i := 1; i < len(words); i++ {
		words[i] = title(words[i])
	}
	return strings.Join(words, "")
}

// Pascal converts a Go field name to PascalCase: CreatedAt, UserId.
//
// Distinct from Exact for exactly the reason Camel is distinct from it:
// splitting normalises a capital run, so HTTPStatus becomes HttpStatus rather
// than being passed through unchanged. Use Exact when the column really is the
// Go spelling.
func Pascal(name string) string {
	words := lowerWords(name)
	for i := range words {
		words[i] = title(words[i])
	}
	return strings.Join(words, "")
}

// Lower lowercases the whole field name: createdat.
//
// This was the behaviour before a Namer could be chosen, and it exists so that
// code relying on it can say so rather than depend on a default. It is almost
// never what a schema looks like; it is here to be named, not to be used.
func Lower(name string) string { return strings.ToLower(name) }

// Exact uses the Go field name verbatim: CreatedAt.
//
// For a schema whose columns are the Go spelling, which happens where the
// tables were generated from these structs. Every dialect here quotes
// identifiers, so a mixed-case column survives.
func Exact(name string) string { return name }

// lowerWords splits a Go field name into lowercased words.
//
// The two rules that are not obvious, both present because their absence
// produced names no schema has:
//
// A run of capitals is one word, broken before its last capital only when a
// lowercase letter follows, because that last capital starts the next word:
// HTTPStatus is HTTP + Status, while HTTP alone is one word.
//
// A trailing lowercase s after a capital run joins that run rather than
// starting a word, because it is a plural and not a word of its own: URLs is
// urls, IDs is ids. Without it the first rule alone gives ur_ls.
func lowerWords(name string) []string {
	r := []rune(name)
	if len(r) == 0 {
		return nil
	}

	var words []string
	start := 0
	for i := 1; i <= len(r); i++ {
		if i == len(r) {
			words = append(words, string(r[start:i]))
			break
		}
		switch {
		// lower or digit, then upper: a new word starts here.
		case !unicode.IsUpper(r[i-1]) && unicode.IsUpper(r[i]):
			words = append(words, string(r[start:i]))
			start = i

		// Inside a run of capitals, with a lowercase letter next: that last
		// capital begins the following word, unless the lowercase letter is a
		// trailing plural s, which belongs to the run.
		case unicode.IsUpper(r[i-1]) && unicode.IsUpper(r[i]) &&
			i+1 < len(r) && unicode.IsLower(r[i+1]) && !pluralS(r, i+1):
			words = append(words, string(r[start:i]))
			start = i
		}
	}

	for i := range words {
		words[i] = strings.ToLower(words[i])
	}
	return words
}

// pluralS reports whether the rune at i is a lowercase s ending the name.
//
// That s is the plural of the capital run before it rather than the start of a
// word, so URLs is urls and IDs is ids. Without this the capital-run rule alone
// gives ur_ls, because it reads the final L as beginning a word called "Ls".
func pluralS(r []rune, i int) bool {
	return r[i] == 's' && i+1 == len(r)
}

// title uppercases the first rune and leaves the rest, which is all that is
// needed here because lowerWords has already lowercased every word.
func title(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
