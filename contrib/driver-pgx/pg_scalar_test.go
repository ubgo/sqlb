// TestPGConstructs_Time executes every date, time and interval construct.
func TestPGConstructs_Time(t *testing.T) {
	db := catalogue(t)
	expr(t, db, "Now", pg.Now())
	expr(t, db, "ClockTimestamp", pg.ClockTimestamp())
	expr(t, db, "StatementTimestamp", pg.StatementTimestamp())
	expr(t, db, "CurrentDate", pg.CurrentDate())
	expr(t, db, "DateTrunc", pg.DateTrunc(pg.FieldMonth, uCreatedAny()))
	expr(t, db, "DateBin", pg.DateBin(pg.Interval("15 minutes"), uCreatedAny(), t0))
	expr(t, db, "Extract", pg.Extract(pg.FieldEpoch, uCreatedAny()))
	for _, f := range []pg.DateField{pg.FieldDay, pg.FieldDow, pg.FieldDoy, pg.FieldHour, pg.FieldIsoDow, pg.FieldIsoYear, pg.FieldMillennium, pg.FieldMinute, pg.FieldQuarter, pg.FieldSecond, pg.FieldTimezone, pg.FieldWeek, pg.FieldYear} {
		expr(t, db, "Extract "+string(f), pg.Extract(f, uCreatedAny()))
	}
	expr(t, db, "AtTimeZone", pg.AtTimeZone(uCreatedAny(), "UTC"))
	expr(t, db, "AddInterval", pg.AddInterval(uCreatedAny(), pg.Interval("1 day")))
	expr(t, db, "SubInterval", pg.SubInterval(uCreatedAny(), pg.Interval("1 day")))
	expr(t, db, "Diff", pg.Diff(uCreatedAny(), uCreatedAny()))
	expr(t, db, "Age", pg.Age(uCreatedAny(), uCreatedAny()))
	expr(t, db, "MakeInterval", pg.MakeInterval(1, 2))
	expr(t, db, "ToTimestamp", pg.ToTimestamp(sqlb.Param("2026-01-15 10:00"), "YYYY-MM-DD HH24:MI"))
	expr(t, db, "ToDate", pg.ToDate(sqlb.Param("2026-01-15"), "YYYY-MM-DD"))
	expr(t, db, "EpochSeconds", pg.EpochSeconds(sqlb.Param(1.5e9)))
	pred(t, db, "OverlapsPeriod", pg.OverlapsPeriod(uCreatedAny(), uCreatedAny(), uCreatedAny(), uCreatedAny()))
	// misc.go / more.go time
	expr(t, db, "IntervalLit", pg.IntervalLit("2 hours"))
	expr(t, db, "AddIntervalExpr", pg.AddIntervalExpr(uCreatedAny(), mIv))
	expr(t, db, "SubIntervalExpr", pg.SubIntervalExpr(uCreatedAny(), mIv))
	gt, gtv := pg.GenerateSeriesTime(t0, t0.Add(48*time.Hour), "1 day", "d")
	executes(t, db, "GenerateSeriesTime", sel().Exprs(gtv).From(gt))
	ge, gev := pg.GenerateSeriesExpr(pg.TimestamptzLit("2026-01-01"), pg.TimestamptzLit("2026-01-03"), pg.IntervalLit("1 day"), "d")
	executes(t, db, "GenerateSeriesExpr", sel().Exprs(gev).From(ge))
	expr(t, db, "ExtractFrom", pg.ExtractFrom(pg.FieldYear, mDay))
	expr(t, db, "DateTruncZone", pg.DateTruncZone(pg.FieldDay, uCreatedAny(), "UTC"))
	expr(t, db, "TimestampLit", pg.TimestampLit("2026-01-15 10:00:00"))
	expr(t, db, "TimestamptzLit", pg.TimestamptzLit("2026-01-15 10:00:00+00"))
	expr(t, db, "DateLit", pg.DateLit("2026-01-15"))
	expr(t, db, "Infinity", pg.Infinity())
	pred(t, db, "OverlapsInterval", pg.OverlapsInterval(uCreatedAny(), mIv, uCreatedAny(), mIv))
	expr(t, db, "IntervalMul", pg.IntervalMul(mIv, sqlb.Cast[int32](sqlb.Param[int32](2), "int")))
	expr(t, db, "JustifyInterval", pg.JustifyInterval(mIv))
	expr(t, db, "DaysBetween", pg.DaysBetween(mDay, mDay))
	expr(t, db, "DatePlusDays", pg.DatePlusDays(mDay, sqlb.Cast[int32](sqlb.Param[int32](3), "int")))
	expr(t, db, "DateMinusDays", pg.DateMinusDays(mDay, sqlb.Cast[int32](sqlb.Param[int32](3), "int")))
	expr(t, db, "UUIDv7Timestamp", pg.UUIDv7Timestamp(mUID))
}

// uCreatedAny is the misc table's timestamptz column as a time expression;
// the misc row carries no timestamp column of its own, so the day column is
// cast.
func uCreatedAny() sqlb.Expr[time.Time] { return sqlb.Cast[time.Time](mDay, "timestamptz") }

