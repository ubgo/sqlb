// TestPGConstructs_Arrays executes every array construct in pg against a
// real Postgres.
func TestPGConstructs_Arrays(t *testing.T) {
	db := catalogue(t)
	expr(t, db, "Array", pg.Array(int32(1), 2, 3))
	pred(t, db, "ArrayContains", pg.ArrayContains(mNums, []int32{1}))
	pred(t, db, "ArrayContainedBy", pg.ArrayContainedBy(mNums, []int32{1, 2, 3, 4}))
	pred(t, db, "Overlaps", pg.Overlaps(mNums, []int32{2, 9}))
	expr(t, db, "ArrayConcat", pg.ArrayConcat(mNums, mNums))
	pred(t, db, "Any", pg.Any(mNums, int32(2)))
	pred(t, db, "AnyOp", pg.AnyOp(mNums, sqlb.OpGreater, int32(2)))
	pred(t, db, "AllOp", pg.AllOp(mNums, sqlb.OpGreater, int32(0)))
	expr(t, db, "Subscript", pg.Subscript(mNums, 1))
	expr(t, db, "Slice", pg.Slice(mNums, 1, 2))
	expr(t, db, "Cardinality", pg.Cardinality(mNums))
	expr(t, db, "ArrayLength", pg.ArrayLength(mNums, 1))
	expr(t, db, "ArrayAppend", pg.ArrayAppend(mNums, int32(9)))
	expr(t, db, "ArrayPrepend", pg.ArrayPrepend(int32(0), mNums))
	expr(t, db, "ArrayRemove", pg.ArrayRemove(mNums, int32(1)))
	expr(t, db, "ArrayReplace", pg.ArrayReplace(mNums, int32(1), int32(7)))
	expr(t, db, "ArrayCat", pg.ArrayCat(mNums, mNums))
	expr(t, db, "ArrayPosition", pg.ArrayPosition(mNums, int32(2)))
	expr(t, db, "ArrayToString", pg.ArrayToString(mNums, ","))
	expr(t, db, "StringToArray", pg.StringToArray(mBody, " "))
	src, el := pg.Unnest(mNums, "n")
	fromSource(t, db, "Unnest", src, el)
	src2, el2, ord := pg.UnnestOrdinal(mNums, "n")
	fromSource(t, db, "UnnestOrdinal", src2, sqlb.Add(sqlb.Cast[int64](el2, "bigint"), ord))
	gs, gv := pg.GenerateSeries(1, 5, 2, "g")
	executes(t, db, "GenerateSeries", sel().Exprs(gv).From(gs))
	sub, si := pg.GenerateSubscripts(mNums, 1, "s")
	fromSource(t, db, "GenerateSubscripts", sub, si)
	pred(t, db, "InArray", pg.InArray(mID, []int64{1, 2}))
	expr(t, db, "ArrayDims", pg.ArrayDims(mNums))
	expr(t, db, "ArrayNDims", pg.ArrayNDims(mNums))
	expr(t, db, "ArrayLower", pg.ArrayLower(mNums, 1))
	expr(t, db, "ArrayUpper", pg.ArrayUpper(mNums, 1))
	since(t, db, 18, "ArrayReverse", sel().Exprs(pg.ArrayReverse(mNums)).From(catMisc))
	since(t, db, 18, "ArraySort", sel().Exprs(pg.ArraySort(mNums)).From(catMisc))
	since(t, db, 18, "ArraySortDesc", sel().Exprs(pg.ArraySortDesc(mNums, true)).From(catMisc))
	expr(t, db, "ArrayShuffle", pg.ArrayShuffle(mNums))
	executes(t, db, "ArraySample", sel().Exprs(pg.ArraySample(mNums, 1)).From(catMisc).Where(sqlb.Eq(mID, int64(1))))
	executes(t, db, "TrimArray", sel().Exprs(pg.TrimArray(mNums, 1)).From(catMisc).Where(sqlb.Eq(mID, int64(1))))
	// misc.go and more.go array constructs
	expr(t, db, "ArrayOf", pg.ArrayOf(mID, sqlb.Param[int64](2)))
	pred(t, db, "AnyExpr", pg.AnyExpr(sqlb.Param[int32](2), sqlb.OpEq, mNums))
	pred(t, db, "AllExpr", pg.AllExpr(sqlb.Param[int32](0), sqlb.OpLess, mNums))
	expr(t, db, "SliceFrom", pg.SliceFrom(mNums, 2))
	expr(t, db, "SliceTo", pg.SliceTo(mNums, 2))
	expr(t, db, "SubscriptExpr", pg.SubscriptExpr(mNums, sqlb.Param[int32](1)))
	expr(t, db, "ArrayPositions", pg.ArrayPositions(mNums, int32(1)))
	expr(t, db, "ArrayRemoveNull", pg.ArrayRemoveNull(mNums))
	expr(t, db, "EmptyArray", pg.EmptyArray[int32]("int4"))
	expr(t, db, "ArrayLit", pg.ArrayLit[int32]("{1,2}", "int4"))
	pred(t, db, "OverlapsExpr", pg.OverlapsExpr(mNums, mNums))
	pred(t, db, "ArrayContainsExpr", pg.ArrayContainsExpr(mNums, mNums))
	pred(t, db, "ArrayContainedByExpr", pg.ArrayContainedByExpr(mNums, mNums))
	expr(t, db, "SliceExprs", pg.SliceExprs(mNums, sqlb.Param[int32](1), sqlb.Param[int32](2)))
	expr(t, db, "UnnestScalar", pg.UnnestScalar(mNums))
	um := pg.UnnestMulti("um", []sqlb.SQLer{mNums, mNums}, true, "a", "b", "ord")
	fromSource(t, db, "UnnestMulti", um, sqlb.Col[int32](sqlb.Ref(um), "a"))
	rf := pg.RowsFrom("rf", []sqlb.SQLer{pg.UnnestScalar(mNums), pg.GenerateSeriesScalar(sqlb.Param[int64](1), sqlb.Param[int64](3))}, true, "a", "b", "ord")
	fromSource(t, db, "RowsFrom", rf, sqlb.Col[int64](sqlb.Ref(rf), "b"))
	expr(t, db, "GenerateSeriesScalar", pg.GenerateSeriesScalar(sqlb.Param[int64](1), sqlb.Param[int64](3)))
	executes(t, db, "ArraySubquery", sel().Exprs(pg.ArraySubquery[int64](sel().Exprs(mID).From(catMisc))))
	executes(t, db, "AnyOf", sel().Exprs(mID).From(catMisc).Where(pg.AnyOf(mID, sqlb.OpEq, sel().Exprs(oUser).From(catOrder))))
	executes(t, db, "AllOf", sel().Exprs(mID).From(catMisc).Where(pg.AllOf(mID, sqlb.OpLessEq, sel().Exprs(oUser).From(catOrder))))
	expr(t, db, "Variadic", pg.Func[string]("format", "format", sqlb.Param("%s-%s"), pg.Variadic(pg.Array("a", "b"))))
}

// TestPGConstructs_JSON executes every jsonb and SQL/JSON construct.
func TestPGConstructs_JSON(t *testing.T) {
	db := catalogue(t)
	expr(t, db, "Get", pg.Get(mDoc, "a"))
	expr(t, db, "GetIndex", pg.GetIndex(mDoc, 0))
	expr(t, db, "JSONText", pg.JSONText(mDoc, "n"))
	expr(t, db, "PathGet", pg.PathGet(mDoc, []string{"a", "b"}))
	expr(t, db, "PathText", pg.PathText(mDoc, []string{"a", "b", "0"}))
	pred(t, db, "Contains", pg.Contains(mDoc, json.RawMessage(`{"n":null}`)))
	pred(t, db, "ContainedBy", pg.ContainedBy(mDoc, json.RawMessage(`{"n":null,"z":1}`)))
	pred(t, db, "HasKey", pg.HasKey(mDoc, "a"))
	pred(t, db, "HasAnyKey", pg.HasAnyKey(mDoc, []string{"a", "q"}))
	pred(t, db, "HasAllKeys", pg.HasAllKeys(mDoc, []string{"a", "tags"}))
	expr(t, db, "JSONConcat", pg.JSONConcat(mDoc, mDoc))
	expr(t, db, "DeleteKey", pg.DeleteKey(mDoc, "n"))
	objExpr(t, db, "DeletePath", pg.DeletePath(mDoc, []string{"a", "b"}))
	pred(t, db, "PathExists", pg.PathExists(mDoc, "$.a.b[*] ? (@ > 1)"))
	pred(t, db, "PathMatch", pg.PathMatch(mDoc, "exists($.a)"))
	objExpr(t, db, "JSONBSet", pg.JSONBSet(mDoc, []string{"a", "c"}, json.RawMessage(`9`), true))
	objExpr(t, db, "JSONBInsert", pg.JSONBInsert(mDoc, []string{"a", "d"}, json.RawMessage(`"new"`)))
	expr(t, db, "BuildObject", pg.BuildObject(pg.Key("id"), mID, pg.Key("body"), mBody))
	expr(t, db, "BuildArray", pg.BuildArray(mID, mBody))
	expr(t, db, "ToJSONB", pg.ToJSONB(mBody))
	expr(t, db, "RowToJSON", pg.RowToJSON(catMisc))
	expr(t, db, "JSONBTypeof", pg.JSONBTypeof(mDoc))
	executes(t, db, "JSONBArrayLength", sel().Exprs(pg.JSONBArrayLength(pg.Get(mDoc, "tags"))).From(catMisc).Where(pg.HasKey(mDoc, "tags")))
	expr(t, db, "StripNulls", pg.StripNulls(mDoc))
	expr(t, db, "Pretty", pg.Pretty(mDoc))
	ae, av := pg.ArrayElements(pg.Get(mDoc, "tags"), "e")
	executes(t, db, "ArrayElements", sel().Exprs(av).From(catMisc).Join(sqlb.Join{Type: sqlb.JoinCross, Source: ae}).Where(pg.HasKey(mDoc, "tags")))
	at, atv := pg.ArrayElementsText(pg.Get(mDoc, "tags"), "e")
	executes(t, db, "ArrayElementsText", sel().Exprs(atv).From(catMisc).Join(sqlb.Join{Type: sqlb.JoinCross, Source: at}).Where(pg.HasKey(mDoc, "tags")))
	ea, ek, ev := pg.Each(mDoc, "kv")
	executes(t, db, "Each", sel().Exprs(ek, ev).From(catMisc).Join(sqlb.Join{Type: sqlb.JoinCross, Source: ea}).Where(pg.HasKey(mDoc, "tags")))
	ok, okv := pg.ObjectKeys(mDoc, "k")
	executes(t, db, "ObjectKeys", sel().Exprs(okv).From(catMisc).Join(sqlb.Join{Type: sqlb.JoinCross, Source: ok}).Where(pg.HasKey(mDoc, "tags")))
	pq, pqv := pg.PathQuery(mDoc, "$.a.b[*]", "p")
	fromSource(t, db, "PathQuery", pq, pqv)
	expr(t, db, "PathQueryFirst", pg.PathQueryFirst(mDoc, "$.a.b[0]"))
	expr(t, db, "JSONBAgg", pg.JSONBAgg(mID))
	expr(t, db, "JSONAgg", pg.JSONAgg(mID))
	expr(t, db, "JSONBObjectAgg", pg.JSONBObjectAgg(sqlb.Cast[string](mID, "text"), mBody))
	// sqljson.go
	expr(t, db, "JSONObject", pg.JSONObject([]pg.JSONPair{pg.Pair("id", mID), pg.Pair("b", mBody)}, pg.AbsentOnNull(), pg.WithUniqueKeys(), pg.ReturningJSONB()))
	expr(t, db, "JSONObject NullOnNull", pg.JSONObject([]pg.JSONPair{pg.Pair("id", mID)}, pg.NullOnNull()))
	expr(t, db, "JSONArrayAgg", pg.JSONArrayAgg(mID, pg.JSONOrderBy(sqlb.OrderBy(mID, sqlb.SortDesc)), pg.ReturningJSONB()))
	expr(t, db, "JSONObjectAgg", pg.JSONObjectAgg(sqlb.Cast[string](mID, "text"), mBody, pg.WithUniqueKeys()))
	pred(t, db, "IsJSON", pg.IsJSON(mBody, pg.JSONAny, false))
	pred(t, db, "IsJSON object unique", pg.IsJSON(sqlb.Cast[string](mDoc, "text"), pg.JSONObj, true))
	expr(t, db, "JSONValue", pg.JSONValue[int64](mDoc, "$.a.b[0]", pg.Returning("bigint"), pg.DefaultOnEmpty("0"), pg.DefaultOnError("-1")))
	expr(t, db, "JSONQuery", pg.JSONQuery(mDoc, "$.a.b[*]", pg.WithWrapper()))
	expr(t, db, "JSONQuery without wrapper", pg.JSONQuery(mDoc, "$.a", pg.WithoutWrapper()))
	expr(t, db, "JSONQuery conditional", pg.JSONQuery(mDoc, "$.a.b[*]", pg.WithConditionalWrapper()))
	pred(t, db, "JSONExists", pg.JSONExists(mDoc, "$.a.b"))
	expr(t, db, "JSONSubscript", pg.JSONSubscript(mDoc, "a", "b"))
	executes(t, db, "SetSubscript", sqlb.NewUpdate(pgd).Table(catMisc).Set(pg.SetSubscript(mDoc, []string{"a", "b"}, sqlb.Param(json.RawMessage(`[9]`)))).Where(sqlb.Eq(mID, int64(1))))
	expr(t, db, "PathQueryArray", pg.PathQueryArray(mDoc, "$.a.b[*]"))
	objExpr(t, db, "JSONBSetLax", pg.JSONBSetLax(mDoc, []string{"a", "c"}, sqlb.Param(json.RawMessage(`null`)), true, "use_json_null"))
	expr(t, db, "JSONNull", pg.JSONNull())
	expr(t, db, "EmptyJSONArray", pg.EmptyJSONArray())
	expr(t, db, "EmptyJSONObject", pg.EmptyJSONObject())
	expr(t, db, "RowRef", pg.ToJSONB(pg.RowRef(catMisc)))
	jt := pg.JSONTable(mDoc, "$.a.b[*]", "jt", pg.JSONTableColumn{Name: "ord", Ordinality: true}, pg.JSONTableColumn{Name: "v", Type: "int", Path: "$", DefaultOnEmpty: "0", DefaultOnError: "-1"}, pg.JSONTableColumn{Name: "has", Type: "bool", Path: "$", Exists: true})
	fromSource(t, db, "JSONTable", jt, sqlb.Col[int32](sqlb.Ref(jt), "v"))
	nested := pg.JSONTable(mDoc, "$", "jn", pg.JSONTableColumn{Name: "n", Type: "text", Path: "$.n"}, pg.JSONTableColumn{Nested: &pg.JSONTableNested{Path: "$.tags[*]", Columns: []pg.JSONTableColumn{{Name: "tag", Type: "text", Path: "$"}}}})
	fromSource(t, db, "JSONTable nested", nested, sqlb.Col[string](sqlb.Ref(nested), "tag"))
	pv, pvv := pg.PathQueryVars(mDoc, "$.a.b[*] ? (@ > $min)", []byte(`{"min":1}`), "pv")
	fromSource(t, db, "PathQueryVars", pv, pvv)
	objExpr(t, db, "JSONBSetExpr", pg.JSONBSetExpr(mDoc, []string{"a", "c"}, sqlb.Param(json.RawMessage(`1`)), true))
	expr(t, db, "ArrayElementsScalar", pg.ArrayElementsScalar(pg.Get(mDoc, "tags")))
	expr(t, db, "PathQueryScalar", pg.PathQueryScalar(mDoc, "$.a.b[*]"))
}
