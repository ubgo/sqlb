// TestAlter_ColumnActionsGroupUnderOneStatement renders the column actions:
// joinable ones share a statement, and RENAME stands alone.
func TestAlter_ColumnActionsGroupUnderOneStatement(t *testing.T) {
	phone := sqlb.Col[*string](tUsers, "phone")
	got := build(t)(pg.AlterTable(tUsers).Clause(
		pg.AddColumnIfNotExists(ddl.Column(phone), pg.ColumnCollate(phone, "C")),
		pg.SetDefault(tNick, ptr("")),
		pg.DropDefault(tNick),
		pg.SetNotNull(tNick),
		pg.DropNotNull(tNick),
		pg.AlterType(tEmail, ddl.RawType[string]("varchar(512)")).Collate("C").Using(pg.Left(tEmail, 512)),
		pg.AddIdentity(tTenantID, pg.ByDefault),
		pg.SetDefaultExpr(tEmail, sqlb.Lower(tEmail)),
		pg.DropColumnIfExists(phone).Cascade(),
	).Build())
	want := `ALTER TABLE "auth"."users" ADD COLUMN IF NOT EXISTS "phone" TEXT COLLATE "C", ` +
		`ALTER COLUMN "nick" SET DEFAULT '', ALTER COLUMN "nick" DROP DEFAULT, ALTER COLUMN "nick" SET NOT NULL, ALTER COLUMN "nick" DROP NOT NULL, ` +
		`ALTER COLUMN "email" SET DATA TYPE varchar(512) COLLATE "C" USING left("email", 512), ` +
		`ALTER COLUMN "tenant_id" ADD GENERATED BY DEFAULT AS IDENTITY, ` +
		`ALTER COLUMN "email" SET DEFAULT (lower("email")), ` +
		`DROP COLUMN IF EXISTS "phone" CASCADE`
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
}

// TestAlter_ConstraintsAndTheTable renders the constraint and table actions,
// with each standalone form in a statement of its own.
func TestAlter_ConstraintsAndTheTable(t *testing.T) {
	renamed := sqlb.Table{Name: "people", Schema: "auth"}
	got := build(t)(pg.AlterTable(tSessions).Clause(
		pg.AddConstraintNotValid(pg.References(tSessUser, tUserID).OnDelete(pg.RefCascade)),
		pg.AddConstraint(pg.Unique(pg.TableConstraint{Table: tSessUser.Table(), Name: "sessions_user_key"}, tSessUser)),
		pg.ValidateConstraint(pg.TableConstraint{Table: tSessions, Name: "sessions_user_fk"}),
		pg.RenameConstraint(pg.TableConstraint{Table: tSessions, Name: "a"}, pg.TableConstraint{Table: tSessions, Name: "b"}),
		pg.DropConstraint(pg.TableConstraint{Table: tSessions, Name: "b"}).IfExists().Cascade(),
		pg.EnableRowLevelSecurity(),
		pg.RenameTo(renamed),
		pg.SetSchema("audit"),
	).Build())
	want := `ALTER TABLE "auth"."sessions" ADD FOREIGN KEY ("user_id") REFERENCES "auth"."users" ("id") ON DELETE CASCADE NOT VALID, ` +
		`ADD CONSTRAINT "sessions_user_key" UNIQUE ("user_id"), VALIDATE CONSTRAINT "sessions_user_fk";
ALTER TABLE "auth"."sessions" RENAME CONSTRAINT "a" TO "b";
ALTER TABLE "auth"."sessions" DROP CONSTRAINT IF EXISTS "b" CASCADE, ENABLE ROW LEVEL SECURITY;
ALTER TABLE "auth"."sessions" RENAME TO "people";
ALTER TABLE "auth"."sessions" SET SCHEMA "audit"`
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
}

// TestAlter_RefusesAnotherTablesColumn pins the table check on every action
// that names a column.
func TestAlter_RefusesAnotherTablesColumn(t *testing.T) {
	for name, c := range map[string]pg.AlterClause{
		"add column":     pg.AddColumnIfNotExists(ddl.Column(tSessID)),
		"drop column":    pg.DropColumnIfExists(tSessID),
		"set default":    pg.SetDefault(tSessID, 1),
		"set not null":   pg.SetNotNull(tSessID),
		"alter type":     pg.AlterType(tSessID, ddl.RawType[int64]("bigint")),
		"add identity":   pg.AddIdentity(tSessID, pg.Always),
		"add constraint": pg.AddConstraint(pg.PrimaryKey(tSessID)),
	} {
		if _, err := pg.AlterTable(tUsers).Clause(c).Build(); !errors.Is(err, ddl.ErrForeignColumn) {
			t.Errorf("%s: got %v, want ErrForeignColumn", name, err)
		}
	}
	if _, err := pg.AlterTable(tUsers).Clause(pg.AddColumnIfNotExists(ddl.Column(tNick), pg.ColumnCollate(tEmail, "C"))).Build(); !errors.Is(err, ddl.ErrUnknownColumn) {
		t.Errorf("a collation for another column on an added one: %v", err)
	}
}

func ptr[T any](v T) *T { return &v }
