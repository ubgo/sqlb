// TestAlterForms_ColumnPartsGroupUnderOneStatement renders the ALTER COLUMN
// actions added in 2026-09-24: an expression changed and dropped, an identity
// changed, restarted and dropped. All six join one statement, because none is
// a standalone form in Postgres's grammar.
func TestAlterForms_ColumnPartsGroupUnderOneStatement(t *testing.T) {
	got := build(t)(pg.AlterTable(tUsers).Clause(
		pg.SetExpression(tEmailLow, sqlb.Upper(tEmail)),
		pg.DropExpression(tEmailLow),
		pg.DropExpression(tEmailLow).IfExists(),
		pg.SetIdentityKind(tUserID, pg.ByDefault),
		pg.RestartIdentity(tUserID),
		pg.RestartIdentity(tUserID).With(100),
		pg.DropIdentity(tUserID).IfExists(),
	).Build())
	want := `ALTER TABLE "auth"."users" ALTER COLUMN "email_lower" SET EXPRESSION AS (upper("email")), ` +
		`ALTER COLUMN "email_lower" DROP EXPRESSION, ` +
		`ALTER COLUMN "email_lower" DROP EXPRESSION IF EXISTS, ` +
		`ALTER COLUMN "id" SET GENERATED BY DEFAULT, ` +
		`ALTER COLUMN "id" RESTART, ` +
		`ALTER COLUMN "id" RESTART WITH 100, ` +
		`ALTER COLUMN "id" DROP IDENTITY IF EXISTS`
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
}

// TestAlterForms_UsingIndexNamesTheIndexBare pins the second half of a
// zero-downtime key migration, and that the index is named without its schema,
// which is the only form Postgres accepts there.
func TestAlterForms_UsingIndexNamesTheIndexBare(t *testing.T) {
	key := pg.TableConstraint{Table: tUsers, Name: "users_email_key"}
	pk := pg.TableConstraint{Table: tUsers, Name: "users_pkey"}
	got := build(t)(pg.AlterTable(tUsers).Clause(
		pg.AddUniqueUsingIndex(key, pg.Index{Schema: "auth", Name: "users_email_key"}),
		pg.AddPrimaryKeyUsingIndex(pk, pg.Index{Schema: "auth", Name: "users_pkey"}),
	).Build())
	want := `ALTER TABLE "auth"."users" ADD CONSTRAINT "users_email_key" UNIQUE USING INDEX "users_email_key", ` +
		`ADD CONSTRAINT "users_pkey" PRIMARY KEY USING INDEX "users_pkey"`
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
}

// TestAlterForms_IndexSchemaMustMatchTheTable pins the other half of
// ErrIndexSchema: the field being set is not the error, disagreeing with the
// table is, so the matching pairs build. An index cannot live outside its
// table's schema at all, which is why the only thing a schema here can be is
// a restatement of the table's or a mistake.
func TestAlterForms_IndexSchemaMustMatchTheTable(t *testing.T) {
	got := build(t)(pg.AlterTable(tUsers).Clause(
		pg.AddUniqueUsingIndex(pg.TableConstraint{Table: tUsers, Name: "users_email_key"}, pg.Index{Schema: "auth", Name: "users_email_key"}),
	).Build())
	if want := `ALTER TABLE "auth"."users" ADD CONSTRAINT "users_email_key" UNIQUE USING INDEX "users_email_key"`; got != want {
		t.Errorf("a matching schema:\ngot  %s\nwant %s", got, want)
	}
	got = build(t)(pg.AlterTable(tBare).Clause(
		pg.AddUniqueUsingIndex(pg.TableConstraint{Table: tBare, Name: "bare_key"}, pg.Index{Name: "bare_key"}),
	).Build())
	if want := `ALTER TABLE "bare" ADD CONSTRAINT "bare_key" UNIQUE USING INDEX "bare_key"`; got != want {
		t.Errorf("two empty schemas:\ngot  %s\nwant %s", got, want)
	}
	// A table naming no schema is resolved through search_path when the
	// statement runs, so an index that names one is an unverifiable claim.
	if _, err := pg.AlterTable(tBare).Clause(
		pg.AddUniqueUsingIndex(pg.TableConstraint{Table: tBare, Name: "bare_key"}, pg.Index{Schema: "public", Name: "bare_key"}),
	).Build(); !errors.Is(err, pg.ErrIndexSchema) {
		t.Errorf("an index schema on an unqualified table: %v", err)
	}
}

// tBare is a table declared with no schema, which Postgres resolves through
// search_path when the statement runs.
var tBare = sqlb.Table{Name: "bare"}

// TestAlterForms_RefuseIncompleteValues pins that each new action fails Build
// rather than rendering half a statement: a constraint or index with no name,
// and an action on a column of another table.
func TestAlterForms_RefuseIncompleteValues(t *testing.T) {
	for name, tc := range map[string]struct {
		clause pg.AlterClause
		want   error
	}{
		"no constraint":           {pg.AddUniqueUsingIndex(pg.TableConstraint{}, pg.Index{Name: "i"}), ddl.ErrZeroValue},
		"no index":                {pg.AddPrimaryKeyUsingIndex(pg.TableConstraint{Table: tUsers, Name: "c"}, pg.Index{}), pg.ErrEmptyName},
		"index in another schema": {pg.AddUniqueUsingIndex(pg.TableConstraint{Table: tUsers, Name: "c"}, pg.Index{Schema: "audit", Name: "i"}), pg.ErrIndexSchema},
		"foreign column":          {pg.SetIdentityKind(tSessID, pg.Always), ddl.ErrForeignColumn},
		"foreign drop":            {pg.DropIdentity(tSessID), ddl.ErrForeignColumn},
		"foreign expr":            {pg.SetExpression(tSessID, tSessID), ddl.ErrForeignColumn},
		"foreign restart":         {pg.RestartIdentity(tSessID), ddl.ErrForeignColumn},
	} {
		if _, err := pg.AlterTable(tUsers).Clause(tc.clause).Build(); !errors.Is(err, tc.want) {
			t.Errorf("%s: got %v, want %v", name, err, tc.want)
		}
	}
}

// TestAlterForms_SequenceOptionsJoinOneStatement renders AS, START WITH and
// the logged options, which Postgres takes together with the options that were
// already built.
func TestAlterForms_SequenceOptionsJoinOneStatement(t *testing.T) {
	seq := pg.Sequence[int32]{Schema: "auth", Name: "invoice_no"}
	got := build(t)(pg.AlterSequence(seq).SetType().StartWith(1000).IncrementBy(10).Build())
	want := `ALTER SEQUENCE "auth"."invoice_no" AS integer START WITH 1000 INCREMENT BY 10`
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
	big := pg.Sequence[int64]{Name: "invoice_no"}
	got = build(t)(pg.AlterSequence(big).SetType().Build())
	if want := `ALTER SEQUENCE "invoice_no" AS bigint`; got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
	got = build(t)(pg.AlterSequence(big).SetUnlogged().Build())
	if want := `ALTER SEQUENCE "invoice_no" SET UNLOGGED`; got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
	got = build(t)(pg.AlterSequence(big).SetLogged().IfExists().Build())
	if want := `ALTER SEQUENCE IF EXISTS "invoice_no" SET LOGGED`; got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
}

// TestAlterForms_SetObjectSchemaNamesTheObjectKind pins that the kind comes
// from the Go type, which is what stops a statement saying VIEW of a sequence.
func TestAlterForms_SetObjectSchemaNamesTheObjectKind(t *testing.T) {
	archive := pg.Schema{Name: "archive"}
	for want, o := range map[string]pg.Movable{
		`ALTER VIEW "auth"."open" SET SCHEMA "archive"`:           pg.View{Schema: "auth", Name: "open"},
		`ALTER MATERIALIZED VIEW "counts" SET SCHEMA "archive"`:   pg.MaterializedView{Name: "counts"},
		`ALTER SEQUENCE "auth"."invoice_no" SET SCHEMA "archive"`: pg.Sequence[int64]{Schema: "auth", Name: "invoice_no"},
		`ALTER TYPE "auth"."status" SET SCHEMA "archive"`:         pg.Enum[string]{Schema: "auth", Name: "status"},
		`ALTER TYPE "money" SET SCHEMA "archive"`:                 pg.Composite[string]{Name: "money"},
		`ALTER DOMAIN "auth"."email" SET SCHEMA "archive"`:        pg.Domain[string]{Schema: "auth", Name: "email"},
	} {
		if got := build(t)(pg.SetObjectSchema(o, archive).Build()); got != want {
			t.Errorf("got  %s\nwant %s", got, want)
		}
	}
	if _, err := pg.SetObjectSchema(pg.View{Name: "v"}, pg.Schema{}).Build(); !errors.Is(err, pg.ErrEmptyName) {
		t.Errorf("a move into an unnamed schema: %v", err)
	}
	if _, err := pg.SetObjectSchema(pg.View{}, archive).Build(); !errors.Is(err, pg.ErrEmptyName) {
		t.Errorf("a move of an unnamed view: %v", err)
	}
}

// TestAlterForms_ViewOptionsSetAndResetAreTwoStatements pins that a builder
// which both sets and resets renders a Script of two, because Postgres keeps
// SET and RESET apart in its grammar.
func TestAlterForms_ViewOptionsSetAndResetAreTwoStatements(t *testing.T) {
	v := pg.View{Schema: "auth", Name: "open"}
	got := build(t)(pg.AlterViewOptions(v).
		SecurityInvoker(true).
		SecurityBarrier(false).
		CheckOption(pg.Cascaded).
		Reset(pg.ViewCheckOption, pg.ViewSecurityBarrier).
		Build())
	want := `ALTER VIEW "auth"."open" SET (security_invoker = true, security_barrier = false, check_option = cascaded);
ALTER VIEW "auth"."open" RESET (check_option, security_barrier)`
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
	if _, err := pg.AlterViewOptions(v).Build(); !errors.Is(err, ddl.ErrZeroValue) {
		t.Errorf("a view options statement with no option: %v", err)
	}
	if _, err := pg.AlterViewOptions(v).CheckOption(pg.CheckOption(0)).Build(); err == nil {
		t.Error("a check option outside the closed set built")
	}
	if _, err := pg.AlterViewOptions(v).Reset(pg.ViewOption(0)).Build(); err == nil {
		t.Error("a view option outside the closed set built")
	}
}

// TestAlterForms_MethodsDoNotWriteToTheirReceiver pins the value semantics of
// the clauses, which the receiver-write gate does not reach: it walks types
// with a Build method, and a clause has none.
func TestAlterForms_MethodsDoNotWriteToTheirReceiver(t *testing.T) {
	base := pg.DropIdentity(tUserID)
	if derived := base.IfExists(); !clauseHas(t, derived, "IF EXISTS") || clauseHas(t, base, "IF EXISTS") {
		t.Error("DropColumnPartClause.IfExists wrote to its receiver")
	}
	r := pg.RestartIdentity(tUserID)
	if derived := r.With(7); !clauseHas(t, derived, "RESTART WITH 7") || clauseHas(t, r, "WITH") {
		t.Error("RestartIdentityClause.With wrote to its receiver")
	}
}

// clauseHas renders one ALTER TABLE action and reports whether it contains s.
func clauseHas(t *testing.T, c pg.AlterClause, s string) bool {
	t.Helper()
	return strings.Contains(build(t)(pg.AlterTable(tUsers).Clause(c).Build()), s)
}
